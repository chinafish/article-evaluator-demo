/**
 * 构建用户提示词
 * @param {Object} article - 文章对象
 * @returns {string} 用户提示词
 */
function buildUserPrompt(article) {
  return `请评估以下文章：

# 文章信息
标题：${article.title}
来源：${article.source || '未知'}
内容：${article.content}

请基于通用认知分析框架，生成包含优先级判断的评估结果。

注意：该文章未匹配到特定行业知识基准，请使用通用认知分析框架进行评估。`;
}

